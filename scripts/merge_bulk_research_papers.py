def main() -> None:
    root = Path(__file__).resolve().parents[1]
    path = root / "frontend" / "src" / "data" / "researchPapers.json"
    data: list[dict] = json.loads(path.read_text(encoding="utf-8"))
    existing_dois = {p.get("doi") for p in data if p.get("doi")}
    to_add = [p for p in NEW if p.get("doi") not in existing_dois]
    if not to_add:
        print("No new papers to append (all DOIs already present).")
        return
    next_id = max(int(p["id"]) for p in data) + 1
    for entry in to_add:
        row = {"id": str(next_id), **entry}
        data.append(row)
        next_id += 1
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Appended {len(to_add)} papers; last id {next_id - 1}")


if __name__ == "__main__":
    main()
