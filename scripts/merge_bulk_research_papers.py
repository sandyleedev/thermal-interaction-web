def paper(
    *,
    title: str,
    authors: str,
    year: int,
    venue: str,
    doi: str,
    min_c: float | None = None,
    max_c: float | None = None,
    dur_min: float | None = None,
    dur_max: float | None = None,
    senses: list[str],
    materials: list[str],
    materials_skin: list[str],
    thermal_modes: list[str],
    body: list[tuple[str, str]],
    ambient: float | None = None,
    thermal_perception_measure: str = "",
    body_parts_involved: str = "",
    purpose: str = "",
    actuator: str = "",
    actuator_model: str = "",
    actuator_size: str = "",
    device_size: str = "",
    temp_range_note: str = "",
    other_actuators: list[str] | None = None,
    aux_hw: list[str] | None = None,
    heat_ctrl: str = "",
    power: str = "",
    temporal: str = "",
    other_note: str = "",
    tech_summary: str = "",
    energy: str = "",
) -> dict:
    """Build one JSON object. Use ``None`` for min/max °C or duration when not reported.

    JSON uses ``null`` (not the string ``\"N/A\"``). Missing temperature or duration bounds
    are stored as ``null`` for all four duplicate keys below.

    Convention: ``dur_min == dur_max == 0`` is treated as unknown (mapped to ``null``),
    since zero is not a meaningful study duration in this dataset.
    """
    other_actuators = other_actuators or []
    aux_hw = aux_hw or []

    if min_c is None or max_c is None:
        min_c = max_c = None
    if dur_min is None or dur_max is None:
        dur_min = dur_max = None
    elif dur_min == 0 and dur_max == 0:
        dur_min = dur_max = None

    return {
        "title": title,
        "authors": authors,
        "publicationYear": year,
        "publicationVenue": venue,
        "doi": doi,
        "url": f"https://doi.org/{doi}",
        "ambientTempC": ambient,
        "minTempC": min_c,
        "maxTempC": max_c,
        "minDurationSec": dur_min,
        "maxDurationSec": dur_max,
        "senses": senses,
        "thermalPerceptionMeasure": thermal_perception_measure,
        "thermalCuePurpose": purpose,
        "thermalTransferModes": thermal_modes,
        "mainActuatorForTemperatureSensation": actuator,
        "mainActuatorModel": actuator_model,
        "mainActuatorSize": actuator_size,
        "overallDeviceSize": device_size,
        "mainActuatorPossibleTemperatureRange": temp_range_note,
        "otherSensoryActuators": other_actuators,
        "auxiliaryHardware": aux_hw,
        "heatControlMethod": heat_ctrl,
        "powerConsumption": power,
        "temporalParameters": temporal,
        "otherNote": other_note,
        "technicalSummary": tech_summary,
        "materialsInContactWithSkin": materials_skin,
        "materials": materials,
        "bodyPartsInvolved": body_parts_involved,
        "bodySites": [{"region": r, "subregion": s} for r, s in body],
        "powerEnergyConsumption": energy,
    }


